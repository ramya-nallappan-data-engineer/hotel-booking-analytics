--Level 1 — Basic Aggregations
--Find the total number of bookings
select count(*) as total_number_of_bookings from bookings;

--Find the total revenue generated (gross_amount) from all bookings
select sum(gross_amount) as total_revenue_generated from bookings;

--Find the average booking value (gross_amount)
select avg(gross_amount) as average_booking_value from bookings;

--Find the minimum and maximum booking value
select min(gross_amount) as minimum_booking_value, max(gross_amount) as maximum_booking_value from bookings;

--Find the average hotel star rating
select avg(star_rating) as average_hotel_star_rating from hotels;

--Find the total number of customers for each loyalty tier
select loyalty_tier, count(customer_id) as total_customers from customers group by loyalty_tier;

--Find the number of hotels in each country
select country, count(hotel_id) as number_of_hotels from hotels group by country;

--Find the number of hotels by hotel type
select hotel_type, count(hotel_id) as number_of_hotels from hotels group by hotel_type;

--Find the number of bookings by booking status
select booking_status, count(booking_id) from bookings group by booking_status;

--Find the number of customers by traveler type
select traveler_type, count(customer_id) as number_of_customers from customers group by traveler_type;

--Level 2 — GROUP BY
--Find the total revenue generated by each hotel
select hotel_id, sum(gross_amount) as total_revenue_generated from bookings group by hotel_id;

--Find the total number of bookings for each hotel
select hotel_id, count(booking_id) as total_number_of_bookings from bookings group by hotel_id;

--Find the average booking value for each booking channel
select booking_channel, avg(gross_amount) from bookings group by booking_channel;

--Find the average stay duration for each room type
select room_type, avg(stay_nights) as average_stay_duration from bookings group by room_type;

--Find the total discount amount given by booking channel
select booking_channel, sum(discount_amount) as total_discount_amount from bookings group by booking_channel;

--Find the total revenue by country
select h.country, sum(gross_amount) as total_revenue from bookings b inner join hotels h on b.hotel_id = h.hotel_id group by h.country;

--Find the total bookings for each booking month
select booking_month, count(booking_id) from bookings group by booking_month;

--Find the average occupancy by hotel
select hotel_id, hotel_name, average_occupancy_rate from hotels;

--Find the average review rating for every hotel
select hotel_id, avg(rating) as average_review_rating from reviews group by hotel_id;

--Find the number of reviews for each hotel
select hotel_id, count(review_id) as number_of_reviews from reviews group by hotel_id;

--Level 3 — GROUP BY + Multiple Aggregations
/*
For every hotel show

Total Bookings
Total Revenue
Average Booking Value
*/
select hotel_id, count(booking_id) as total_bookings, sum(gross_amount) as total_revenue, avg(gross_amount) as average_booking_value
from bookings
group by hotel_id;

/*
For every customer segment show

Number of Customers
Average Age (if available in your dataset)
Active Customers
*/
select customer_segment, count(customer_id) as number_of_customers, count(is_active) as active_customers_count
from customers where is_active=True
group by customer_segment;

/*
For every hotel chain show

Number of Hotels
Average Star Rating
Total Rooms
*/
select hotel_chain, count(hotel_id) as number_of_hotels, avg(star_rating) as average_star_rating, sum(room_count) as total_rooms
from hotels
group by hotel_chain;

/*
For every booking channel show

Total Revenue
Total Discounts
Average Revenue
*/
select booking_channel, sum(gross_amount) as total_revenue, sum(discount_amount) as total_discount_amount, avg(gross_amount) as average_revenue
from bookings
group by booking_channel;

/*
For each country show

Hotels
Customers
Total Bookings
*/
select h.country, count(h.hotel_id) as number_of_hotels, count(c.customer_id) as number_of_customers,
count(b.booking_id) as total_bookings
from bookings b
inner join hotels h on h.hotel_id = b.hotel_id
inner join customers c on b.customer_id = c.customer_id
group by h.country;

--Level 4 — HAVING
--Show hotels having more than 100 bookings
select hotel_id, count(booking_id) as total_number_of_bookings
from bookings
group by hotel_id
having count(booking_id) > 100;

--Show countries having more than 5 hotels
select h.country, count(b.hotel_id)
from bookings b
inner join hotels h on h.hotel_id = b.hotel_id
group by h.country
having count(h.hotel_id) > 5;

--Show hotel chains having an average rating greater than 4
select hotel_chain, avg(rating) as average_rating
from hotels h
inner join reviews r on h.hotel_id = r.hotel_id
group by hotel_chain
having avg(rating) > 4;

--Show booking channels whose revenue exceeds 100,000
select booking_channel, sum(gross_amount) as total_revenue
from bookings
group by booking_channel
having sum(gross_amount) > 100000;

--Show hotels whose average booking value is greater than the overall average booking value
select hotel_id, avg(gross_amount) as average_booking_value
from bookings
group by hotel_id
having avg(gross_amount) >
(select avg(gross_amount) as overall_average_booking_value
from bookings) order by hotel_id asc;

--Find customer segments having more than 50 customers
select customer_segment, count(customer_id) as number_of_customers
from customers
group by customer_segment
having count(customer_id) > 50;

--Find room types whose average stay duration exceeds 5 nights
select room_type, avg(stay_nights) as average_stay_duration
from bookings
group by room_type
having avg(stay_nights) > 5;

--Find hotels having at least 20 reviews
select h.hotel_name, count(rating) as total_reviews
from hotels h
inner join reviews r on h.hotel_id = r.hotel_id
group by h.hotel_name
having count(rating) >= 20;

--Find countries where average hotel rating exceeds 4
select country, avg(rating) as average_hotel_rating
from hotels h
inner join reviews r on h.hotel_id = r.hotel_id
group by country
having avg(rating) > 4;

--Find booking months where bookings exceeded 500
select booking_month, count(booking_id) as total_bookings
from bookings
group by booking_month
having count(booking_id) > 500;

