--Agoda Interview Bonus Questions
--What percentage of bookings came from each booking channel?
with total_bookings as
(select count(booking_id) as total_bookings from bookings),
per_booking_channel_bookings as
(select booking_channel, count(booking_id) as total_bookings_per_channel from bookings group by booking_channel)
select booking_channel, total_bookings_per_channel/tb.total_bookings*100 as percentage_of_bookings
from total_bookings tb, per_booking_channel_bookings pb;

--Find the average revenue generated per customer
select b.customer_id, customer_name, avg(gross_amount) as average_revenue
from bookings b
inner join customers c on c.customer_id = b.customer_id
group by b.customer_id, customer_name
order by b.customer_id asc;

--Find hotels whose revenue contributes more than 5% of the total company revenue
with total_revenue as (select sum(gross_amount) as total_revenue from bookings),
per_hotel_revenue as (select hotel_id, sum(gross_amount) as total_revenue_per_hotel
from bookings
group by hotel_id)
select hotel_id, total_revenue_per_hotel/total_revenue*100 as revenue_contribution_percentage
from total_revenue, per_hotel_revenue
where (total_revenue_per_hotel/total_revenue*100) > 5;

--Find the booking channel with the highest cancellation rate.
with booking_channel_revenue as (select booking_channel, sum(gross_amount) as total_revenue from bookings group by booking_channel),
cancellation_channel_revenue as (select booking_channel, sum(gross_amount) as total_revenue_per_channel from bookings
where booking_status='Cancelled' group by booking_channel)
select bcr.booking_channel, total_revenue_per_channel/total_revenue as cancellation_rate
from booking_channel_revenue bcr inner join cancellation_channel_revenue ccr
on bcr.booking_channel = ccr.booking_channel
order by cancellation_rate desc
limit 1;

--Find countries where customers spend the most per booking
select booking_id, h.country, sum(gross_amount) as total_spent
from bookings b inner join hotels h
on h.hotel_id = b.hotel_id
group by booking_id, h.country
order by total_spent desc;

--Challenge Questions
--Find hotels that earn more from add-on products than room bookings
select b.hotel_id, h.hotel_name, sum(o.total_price) as add_on_revenue, sum(b.gross_amount) as booking_revenue
from bookings b
inner join hotels h on h.hotel_id = b.hotel_id
inner join order_items o on o.booking_id = b.booking_id and o.hotel_id=h.hotel_id
group by b.hotel_id, h.hotel_name
having sum(o.total_price) > sum(b.gross_amount);

--Find hotel chains with the highest occupancy.
select hotel_chain, average_occupancy_rate from hotels order by average_occupancy_rate desc limit 1;

--Find booking months with the highest average discount
select booking_month, avg(discount_amount) as average_discount
from bookings group by booking_month
order by average_discount desc
limit 1;

--Find the revenue split between domestic and international travelers.
select case when country='India' then 'Domestic' else 'International' end as Type_of_travelers,
sum(gross_amount) as total_revenue
from bookings b
inner join hotels h on h.hotel_id = b.hotel_id
group by case when country='India' then 'Domestic' else 'International' end;

