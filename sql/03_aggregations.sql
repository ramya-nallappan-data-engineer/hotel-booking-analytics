--Level 6 — Business KPIs
--Calculate the cancellation rate
with total_bookings as (select count(*) as total_bookings from bookings),
cancelled_bookings as (select count(*) as total_cancelled_bookings from bookings where booking_status = 'Cancelled')
select total_cancelled_bookings/total_bookings*100 as cancellation_rate from total_bookings,cancelled_bookings;

--Calculate the average revenue per booking.
select booking_id, avg(gross_amount) as average_revenue
