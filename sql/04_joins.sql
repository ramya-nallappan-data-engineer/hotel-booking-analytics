/*
Explain the difference between INNER JOIN and LEFT JOIN with a business example from our hotel dataset.
    INNER JOIN - returns only matching result set based on ON condition.
        select hotel_name, booking_id from hotels h inner join bookings b on h.hotel_id = b.hotel_id; --returns hotels with only bookings made
    LEFT JOIN - returns all rows from LEFT table even if no matching keys.
        select hotel_name, booking_id from hotels h left join bookings b on h.hotel_id = b.hotel_id; --returns all hotels even if no bookings made
When would you choose EXISTS instead of JOIN?
    When we wanted to check the presence of a row - choose EXISTS
    When we wanted to identify all matching rows and fetch data from the table - Use JOIN
Why can joins create duplicate rows?
    There are many possibilities,
        - Due to missing primary key or incorrect primary key created, which leads to redundant data in table itself
        - Due to incorrect JOINs used. Joins should ideally be on the primary key from one table to the foreign key to the other table, which will eliminate the duplicates.
What is the difference between filtering in the ON clause and filtering in the WHERE clause?
    Filtering in the ON clause - would ideally fetch/remove the rows from the table
    Filtering in the WHERE clause - would apply the filter condition on the resulting rows after tables are joined
If a join query is running slowly on a table with 500 million rows, what steps would you take to investigate and optimize it?
    - Fetch the EXPLAIN PLAN
    - Analyse the JOINS, HINTS used if any, WHERE clause, OR operator usage, INDEX usage
    - Tune and optimize the query as per the explain plan analysis
